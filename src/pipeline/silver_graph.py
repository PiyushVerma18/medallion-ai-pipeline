def _dq_sql_expression(report: Any, column_name: str) -> str:
    """Return the agent-authored SQL expression for a catalog column.

    The agent prompt instructs expressions to qualify source fields as ``raw.<name>``;
    the source CTE uses ``raw`` as its alias.
    """
    matches = [rule for rule in report.column_rules if rule.column_name == column_name]
    if len(matches) != 1 or not matches[0].sql_transformation.strip():
        raise ValueError(f"DQ report must contain exactly one SQL transformation for {column_name!r}")
    return validate_agent_expression(matches[0].sql_transformation)


def _dq_input_cte(state: PipelineState) -> str:
    """Compile all column-level SQL transformations generated by Agent 1 into a CTE."""
    report = state.get("dq_audit_report")
    if report is None:
        raise ValueError("Silver materialization requires dq_audit_report from the DQ agent")
    selected = [
        f"({_dq_sql_expression(report, rule.column_name)}) AS dq_{rule.column_name}"
        for rule in report.column_rules
    ]
    return (
        "dq_input AS (SELECT raw.*, " + ", ".join(selected) +
        f" FROM {state['bronze_schema']}.{state['bronze_table']} raw)"
    )


