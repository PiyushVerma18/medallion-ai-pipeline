"""Append-only Bronze ingestion with replay-safe file and row lineage."""

import hashlib
import json
import os
from pathlib import Path

import pandas as pd
from sqlalchemy import text

from src.db import engine
from src.pipeline.stage_logging import configure_pipeline_logging, log_stage


BRONZE_DDL = """
CREATE SCHEMA IF NOT EXISTS bronze;

CREATE TABLE IF NOT EXISTS bronze.raw_tickets (
    _bronze_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    _source_file VARCHAR(1024) NOT NULL,
    _source_file_hash VARCHAR(64) NOT NULL,
    _source_row_number BIGINT NOT NULL,
    _ingested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    _row_hash VARCHAR(64) NOT NULL,
    _raw_data JSONB NOT NULL,

    -- Known columns are retained for compatibility with the Silver pipeline.
    -- New source columns are preserved in _raw_data without a DDL change.
    ticket_id TEXT,
    created_at TEXT,
    resolved_at TEXT,
    category TEXT,
    priority TEXT,
    status TEXT,
    building TEXT,
    description TEXT,
    submitted_by TEXT,
    assigned_to TEXT,
    resolution_notes TEXT,
    cost TEXT,
    sla_hours TEXT,

    CONSTRAINT uq_bronze_source_row UNIQUE (_source_file_hash, _source_row_number)
);
"""

# Upgrade databases created by the earlier fixed-column Bronze table. Existing
# rows are retained and assigned a stable legacy source row identity.
BRONZE_MIGRATION_SQL = """
ALTER TABLE bronze.raw_tickets
    ADD COLUMN IF NOT EXISTS _bronze_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS _source_file_hash VARCHAR(64),
    ADD COLUMN IF NOT EXISTS _source_row_number BIGINT,
    ADD COLUMN IF NOT EXISTS _raw_data JSONB;

DO $$
DECLARE pk_name TEXT;
DECLARE pk_definition TEXT;
BEGIN
    SELECT c.conname, pg_get_constraintdef(c.oid)
      INTO pk_name, pk_definition
      FROM pg_constraint c
     WHERE c.conrelid = 'bronze.raw_tickets'::regclass
       AND c.contype = 'p';

    IF pk_name IS NOT NULL AND pk_definition NOT LIKE '%(_bronze_id)%' THEN
        EXECUTE format('ALTER TABLE bronze.raw_tickets DROP CONSTRAINT %I', pk_name);
        pk_name := NULL;
    END IF;
    IF pk_name IS NULL THEN
        ALTER TABLE bronze.raw_tickets
            ADD CONSTRAINT raw_tickets_pkey PRIMARY KEY (_bronze_id);
    END IF;
END $$;

WITH numbered AS (
    SELECT ctid,
           row_number() OVER (PARTITION BY _source_file ORDER BY ctid) AS rn
      FROM bronze.raw_tickets
     WHERE _source_row_number IS NULL
)
UPDATE bronze.raw_tickets b
   SET _source_file_hash = COALESCE(b._source_file_hash, md5(b._source_file)),
       _source_row_number = numbered.rn,
       _raw_data = COALESCE(b._raw_data, jsonb_build_object(
           'ticket_id', b.ticket_id,
           'created_at', b.created_at,
           'resolved_at', b.resolved_at,
           'category', b.category,
           'priority', b.priority,
           'status', b.status,
           'building', b.building,
           'description', b.description,
           'submitted_by', b.submitted_by,
           'assigned_to', b.assigned_to,
           'resolution_notes', b.resolution_notes,
           'cost', b.cost,
           'sla_hours', b.sla_hours
       ))
  FROM numbered
 WHERE b.ctid = numbered.ctid;

ALTER TABLE bronze.raw_tickets
    ALTER COLUMN _source_file_hash SET NOT NULL,
    ALTER COLUMN _source_row_number SET NOT NULL,
    ALTER COLUMN _raw_data SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
         WHERE conrelid = 'bronze.raw_tickets'::regclass
           AND conname = 'uq_bronze_source_row'
    ) THEN
        ALTER TABLE bronze.raw_tickets
            ADD CONSTRAINT uq_bronze_source_row
            UNIQUE (_source_file_hash, _source_row_number);
    END IF;
END $$;
"""


def compute_row_hash(row: dict) -> str:
    """Hash the complete raw row deterministically; this is not a unique key."""
    canonical = json.dumps(
        row,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _file_sha256(file_path: str) -> str:
    digest = hashlib.sha256()
    with open(file_path, "rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


@log_stage("bronze.ingest")
def ingest_bronze(file_path: str = "data/raw_tickets.csv") -> dict:
    """Load all CSV rows into Bronze, preserving duplicates and unknown fields.

    Re-running the same file content is idempotent. Repeated identical rows
    within that file remain separate because their source row numbers differ.
    """
    source_path = Path(file_path)
    if not source_path.is_file():
        raise FileNotFoundError(f"Source file not found at: {file_path}")

    source_file_hash = _file_sha256(str(source_path))
    source_file = str(source_path.resolve())
    print(f"[Bronze] Reading raw file: {source_file}")

    # Keep all values as strings and don't convert empty strings to NaN. The
    # JSON payload retains every source column, including columns added later.
    df = pd.read_csv(source_path, dtype=str, keep_default_na=False)
    raw_columns = list(df.columns)
    known_columns = [
        "ticket_id", "created_at", "resolved_at", "category", "priority",
        "status", "building", "description", "submitted_by", "assigned_to",
        "resolution_notes", "cost", "sla_hours",
    ]

    records = []
    for row_number, values in enumerate(df.to_dict(orient="records"), start=1):
        # Keep column order in the payload as it appeared in the CSV.
        raw_data = {column: values[column] for column in raw_columns}
        record = {
            "_source_file": source_file,
            "_source_file_hash": source_file_hash,
            "_source_row_number": row_number,
            "_row_hash": compute_row_hash(raw_data),
            "_raw_data": json.dumps(raw_data, ensure_ascii=False),
        }
        record.update({column: raw_data.get(column) for column in known_columns})
        records.append(record)

    with engine.begin() as conn:
        conn.execute(text(BRONZE_DDL))
        conn.execute(text(BRONZE_MIGRATION_SQL))

        if records:
            # A temporary staging table avoids per-row INSERT round trips.
            conn.execute(text("""
                CREATE TEMP TABLE temp_stage_bronze (
                    _source_file TEXT NOT NULL,
                    _source_file_hash VARCHAR(64) NOT NULL,
                    _source_row_number BIGINT NOT NULL,
                    _row_hash VARCHAR(64) NOT NULL,
                    _raw_data TEXT NOT NULL,
                    ticket_id TEXT, created_at TEXT, resolved_at TEXT,
                    category TEXT, priority TEXT, status TEXT, building TEXT,
                    description TEXT, submitted_by TEXT, assigned_to TEXT,
                    resolution_notes TEXT, cost TEXT, sla_hours TEXT
                ) ON COMMIT DROP;
            """))
            pd.DataFrame.from_records(records).to_sql(
                "temp_stage_bronze", con=conn, if_exists="append", index=False,
                method="multi", chunksize=1000,
            )
            inserted_rows = conn.execute(text("""
                INSERT INTO bronze.raw_tickets (
                    _source_file, _source_file_hash, _source_row_number,
                    _row_hash, _raw_data,
                    ticket_id, created_at, resolved_at, category, priority,
                    status, building, description, submitted_by, assigned_to,
                    resolution_notes, cost, sla_hours
                )
                SELECT
                    _source_file, _source_file_hash, _source_row_number,
                    _row_hash, _raw_data::jsonb,
                    ticket_id, created_at, resolved_at, category, priority,
                    status, building, description, submitted_by, assigned_to,
                    resolution_notes, cost, sla_hours
                FROM temp_stage_bronze
                ON CONFLICT (_source_file_hash, _source_row_number) DO NOTHING;
            """)).rowcount
        else:
            inserted_rows = 0

        total_bronze = conn.execute(
            text("SELECT COUNT(*) FROM bronze.raw_tickets")
        ).scalar_one()

    print(
        f"[Bronze] Complete. Source rows: {len(df)} | Newly inserted: "
        f"{inserted_rows} | Total Bronze rows: {total_bronze}"
    )
    return {
        "source_rows": len(df),
        "new_inserted": inserted_rows,
        "total_bronze_records": total_bronze,
        "source_file_hash": source_file_hash,
    }


if __name__ == "__main__":
    configure_pipeline_logging()
    ingest_bronze()
